--
-- Structure de la vue `taux_reussite`
--
DROP TABLE IF EXISTS `taux_reussite`;

CREATE ALGORITHM=UNDEFINED DEFINER=`root`@`localhost` SQL SECURITY DEFINER VIEW `taux_reussite`  AS SELECT `robot`.`id_robot` AS `id_robot`, `robot`.`nom_robot` AS `nom_robot`, round(count(case when `action`.`reussite_robot` = 1 then 1 end) * 100 / count(`robot`.`nom_robot`),1) AS `taux_reussite` FROM (`robot` join `action` on(`action`.`id_robot` = `robot`.`id_robot`)) GROUP BY `robot`.`nom_robot` ;

